#include "Profiling.hpp"
#include <cstdio>
#include <cstdarg>
#include <array>
#include <cstdint>
#include <cstring>
#include <limits>
#include <memory>
#include <new>
#include <mutex>
#include <iostream>

namespace aila {

namespace {
    // Global state protected by mutex
    std::mutex g_log_mutex;
    LogCallback g_log_callback = nullptr;
    void* g_log_user_data = nullptr;
    LogLevel g_min_level = LogLevel::Info;

    // Default handler: route logs to stderr so CLI stdout stays usable
    // for streamed/generated model text and shell piping.
    void default_log_handler(LogLevel level, const char* message) {
        (void)level;
        std::cerr << message << std::endl;
    }

    struct DeferredLogHeader {
        LogLevel level;
        uint32_t bytes; // Includes the terminating NUL.
    };

    struct DeferredLogBuffer {
        std::array<char, ScopedLogDeferral::MaxBufferedBytes> bytes;
    };

    struct DeferredLogState {
        std::size_t depth = 0;
        std::size_t usedBytes = 0;
        std::size_t messages = 0;
        std::size_t dropped = 0;
        bool flushing = false;
        bool emittingSummary = false;
        // Allocate only when a scope actually logs; retain one bounded arena
        // per participating thread. No callback pointers are stored here.
        std::unique_ptr<DeferredLogBuffer> buffer;

        void Drop() noexcept {
            if (dropped != (std::numeric_limits<std::size_t>::max)()) ++dropped;
        }

        void Enqueue(LogLevel level, const char* message) noexcept {
            const std::size_t bytes = std::strlen(message) + 1;
            const std::size_t needed = sizeof(DeferredLogHeader) + bytes;
            if (emittingSummary || messages >= ScopedLogDeferral::MaxBufferedMessages ||
                needed > ScopedLogDeferral::MaxBufferedBytes - usedBytes) {
                Drop();
                return;
            }
            if (!buffer) {
                buffer.reset(new (std::nothrow) DeferredLogBuffer);
                if (!buffer) {
                    Drop();
                    return;
                }
            }
            const DeferredLogHeader header{level, static_cast<uint32_t>(bytes)};
            std::memcpy(buffer->bytes.data() + usedBytes, &header, sizeof(header));
            usedBytes += sizeof(header);
            std::memcpy(buffer->bytes.data() + usedBytes, message, bytes);
            usedBytes += bytes;
            ++messages;
        }
    };

    thread_local DeferredLogState g_deferred_logs;

    void deliver_deferred(LogLevel level, const char* message) noexcept {
        try {
            LogCallback callback;
            void* user_data;
            {
                std::lock_guard<std::mutex> lock(g_log_mutex);
                callback = g_log_callback;
                user_data = g_log_user_data;
            }
            // A callback may replace the registration or call into Aila.
            if (callback) callback(static_cast<int>(level), message, user_data);
            else default_log_handler(level, message);
        } catch (...) {
            // Logging cannot throw out of a scope destructor or change a
            // request's result. Continue delivering the remaining records.
        }
    }

    void flush_deferred(DeferredLogState& state) noexcept {
        state.flushing = true;
        std::size_t offset = 0;
        // Reentrant logs append to the same arena. Do not reclaim consumed
        // records here: the byte/message bounds also cap recursive logging.
        while (offset < state.usedBytes) {
            DeferredLogHeader header;
            std::memcpy(&header, state.buffer->bytes.data() + offset, sizeof(header));
            offset += sizeof(header);
            const char* message = state.buffer->bytes.data() + offset;
            offset += header.bytes;
            deliver_deferred(header.level, message);
        }
        if (state.dropped != 0) {
            state.emittingSummary = true;
            char summary[160];
            std::snprintf(summary, sizeof(summary),
                          "[Aila] Deferred log buffer limit reached; dropped at least %zu message(s).",
                          state.dropped);
            // Logs generated by this one summary callback are dropped too.
            deliver_deferred(LogLevel::Warning, summary);
        }
        state.usedBytes = 0;
        state.messages = 0;
        state.dropped = 0;
        state.emittingSummary = false;
        state.flushing = false;
    }
} // namespace

ScopedLogDeferral::ScopedLogDeferral() noexcept {
    ++g_deferred_logs.depth;
}

ScopedLogDeferral::~ScopedLogDeferral() noexcept {
    if (--g_deferred_logs.depth == 0 && !g_deferred_logs.flushing) {
        flush_deferred(g_deferred_logs);
    }
}

void set_log_callback(LogCallback cb, void* user_data) {
    std::lock_guard<std::mutex> lock(g_log_mutex);
    g_log_callback = cb;
    g_log_user_data = user_data;
}

void set_log_level(LogLevel level) {
    std::lock_guard<std::mutex> lock(g_log_mutex);
    g_min_level = level;
}

LogLevel get_log_level() {
    std::lock_guard<std::mutex> lock(g_log_mutex);
    return g_min_level;
}

void vlog(LogLevel level, const char* fmt, va_list args) {
    LogCallback cb;
    void* ud;
    LogLevel min_level;
    {
        std::lock_guard<std::mutex> lock(g_log_mutex);
        cb = g_log_callback;
        ud = g_log_user_data;
        min_level = g_min_level;
    }

    if (level < min_level) return;

    char buf[2048];
    vsnprintf(buf, sizeof(buf), fmt, args);

    if (g_deferred_logs.depth != 0 || g_deferred_logs.flushing) {
        g_deferred_logs.Enqueue(level, buf);
        return;
    }

    if (cb) {
        cb(static_cast<int>(level), buf, ud);
    } else {
        default_log_handler(level, buf);
    }
}

void log(LogLevel level, const char* fmt, ...) {
    va_list args;
    va_start(args, fmt);
    vlog(level, fmt, args);
    va_end(args);
}

} // namespace aila
